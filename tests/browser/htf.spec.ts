import {test,expect} from '@playwright/test';
import {readFileSync} from 'node:fs';
import type {Timeframe} from '../../lib/candle-data';
const fixture=JSON.parse(readFileSync('tests/fixtures/htf-NAS100.json','utf8'));
test('V5 chart exposes author research and refresh; removed generic SNR controls cannot emit evidence',async({page})=>{
 const errors:string[]=[];page.on('pageerror',e=>errors.push(e.message));
 let legacyCalls=0;
 await page.route('**/api/candles?**',route=>route.fulfill({json:fixture.data[new URL(route.request().url()).searchParams.get('timeframe') as Timeframe]}));
 await page.route('**/api/htf-zones?**',route=>{legacyCalls++;return route.fulfill({status:503,json:{ok:false}});});
 await page.goto('/');await page.getByRole('button',{name:'W1',exact:true}).click();
 const panel=page.getByRole('region',{name:'Техническая структура Capitalive'});
 await expect(panel.getByRole('link',{name:'THE EDGE Research Desk'})).toHaveAttribute('href','/intelligence');
 await expect(panel.getByRole('link',{name:'Получить свежий отчёт'})).toHaveAttribute('href','/research');
 await expect(panel.getByLabel('Weekly SNR',{exact:true})).toHaveCount(0);
 await expect(panel.locator('[data-snr-timeframe],[data-snr-state]')).toHaveCount(0);
 await expect(panel.getByRole('link',{name:'Открыть PNG'})).toHaveAttribute('href',/snr_w1=0/);
 await page.getByRole('button',{name:'ASK',exact:true}).click();
 await page.setViewportSize({width:390,height:844});expect(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth)).toBe(true);
 expect(legacyCalls).toBe(0);expect(errors).toEqual([]);
});
